def test_garch_recovers_the_simulated_parameters():
    """Fit the model to data generated by a known GJR-GARCH.

    Tolerances are loose on the individual terms and tighter on the persistence,
    because that is what the likelihood surface actually identifies: ``alpha`` and
    ``gamma`` trade off against each other (both are quadratic-in-return terms) far
    more than either trades off against ``beta``. A test that demanded each
    coefficient to two decimals would fail on a different seed and teach nothing.
    """
    truth = {"alpha": 0.07, "gamma": 0.11, "beta": 0.85}
    persistence = truth["alpha"] + truth["beta"] + 0.5 * truth["gamma"]
    sigma2_uncond = 0.012**2
    omega = (1.0 - persistence) * sigma2_uncond

    rng = np.random.default_rng(23)
    z = rng.standard_t(cfg.SIM_T_DOF, size=60_000) / np.sqrt(cfg.SIM_T_DOF / (cfg.SIM_T_DOF - 2))
    path = kernels.garch_simulate_path(omega, truth["alpha"], truth["gamma"], truth["beta"], z, sigma2_uncond)
    returns = np.sqrt(path) * z

    model = volmodels.GARCH(kind="gjr")
    model.fit(returns, pd.DataFrame(index=pd.RangeIndex(returns.size)), returns.size)
    fit = model.params
    assert fit["alpha"] + fit["beta"] + 0.5 * fit["gamma"] == pytest.approx(persistence, abs=0.08)
    assert fit["beta"] == pytest.approx(truth["beta"], abs=0.15)
    assert fit["dof"] > 2.05


def test_garch_converges_rather_than_returning_the_initial_point(returns, features):
    """The failure mode this guards against is silent: L-BFGS-B reporting nit=0.

    With scipy's default line-search budget the optimiser runs out of backtracking
    steps on the first iteration, reports success, and returns the starting guess
    while quoting a function value it never attained. The observable symptom is a
    likelihood equal to the value at ``theta0`` - so the comparison has to be made
    against the starting point of *this* fit, not against a warm start from a model
    that has already been fitted.
    """
    r = returns.to_numpy(dtype=float)
    model = volmodels.GARCH(kind="gjr")
    theta0 = model._initial(r)
    assert model.params == {}

    model.fit(r, features, r.size)
    assert model.params["neg_loglik"] < model._neg_loglik(theta0, r)
    assert not np.allclose(model.params["theta"], theta0)
    assert model.params["alpha"] + model.params["beta"] > 0.5
    assert model.params["dof"] > 2.05


def test_egarch_forecast_is_strictly_positive(returns, features):
    model = volmodels.GARCH(kind="egarch")
    model.fit(returns.to_numpy(dtype=float), features, 1_500)
    out = model.forecast(returns.to_numpy(dtype=float), features, 1_500, 1_700)
    assert np.isfinite(out).all()
    assert (out > 0).all()


def test_garch_forecast_ignores_data_after_the_forecast_day(returns, features):
    """The legality check for the recursions."""
    r = returns.to_numpy(dtype=float)
    model = volmodels.GARCH(kind="gjr")
    model.fit(r, features, 1_200)
    baseline = model.forecast(r, features, 1_200, 1_260)

    poisoned = r.copy()
    poisoned[1_300:1_500] *= 6.0
    after = model.forecast(poisoned, features, 1_200, 1_260)
    assert np.allclose(baseline, after, rtol=1e-12)


def test_garch_forecast_reacts_to_data_before_the_forecast_day(returns, features):
    """The complement of the previous test: the model is not simply ignoring input."""
    r = returns.to_numpy(dtype=float)
    model = volmodels.GARCH(kind="gjr")
    model.fit(r, features, 1_200)
    baseline = model.forecast(r, features, 1_200, 1_201)

    poisoned = r.copy()
    poisoned[1_100:1_200] *= 5.0
    after = model.forecast(poisoned, features, 1_200, 1_201)
    assert after[0] > baseline[0]


def test_variance_targeting_reproduces_the_sample_variance(returns, features, garch_fit):
    r = returns.to_numpy(dtype=float)
    p = garch_fit.params
    implied = (1.0 - p["alpha"] - p["beta"] - 0.5 * p["gamma"]) * p["unconditional_variance"]
    assert implied > 0
    assert p["unconditional_variance"] == pytest.approx(float(np.var(r)), rel=1e-9)


