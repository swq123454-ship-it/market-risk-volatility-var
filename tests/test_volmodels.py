def test_walk_forward_leaves_the_burn_in_empty(returns, features):
    zoo = [volmodels.RollingVariance(window=21), volmodels.EWMA(lam=0.94)]
    forecasts = volmodels.walk_forward(zoo, returns, features, init_window=500, refit_every=100)
    assert forecasts.variance.index.equals(returns.index)
    assert forecasts.variance.iloc[:500].isna().all().all()
    assert forecasts.variance.iloc[500:].notna().all().all()


def test_walk_forward_does_not_look_ahead(returns, features):
    """Corrupt the evaluation tail; the early forecasts must not move.

    This is the strongest statement the engine can make. It holds because
    parameters are frozen between refits and the state is filtered with realised
    returns, so a forecast on day ``t`` depends on ``r[:t]`` and on parameters
    estimated at or before ``t`` - and a corruption strictly after the refit block
    touches neither.
    """
    zoo = [volmodels.RollingVariance(window=21), volmodels.EWMA(lam=0.94), volmodels.GARCH(kind="gjr")]
    baseline = volmodels.walk_forward(zoo, returns, features, init_window=1_000, refit_every=250)

    poisoned = returns.copy()
    poisoned.iloc[1_100:] *= -6.0
    after = volmodels.walk_forward(zoo, poisoned, features, init_window=1_000, refit_every=250)

    for name in baseline.variance.columns:
        left = baseline.variance[name].iloc[1_000:1_100].to_numpy()
        right = after.variance[name].iloc[1_000:1_100].to_numpy()
        assert np.allclose(left, right, rtol=1e-10), name


def test_walk_forward_refits_on_the_declared_schedule(returns, features):
    zoo = [volmodels.EWMA(lam=0.94)]
    forecasts = volmodels.walk_forward(zoo, returns, features, init_window=1_000, refit_every=250)
    expected = list(range(1_000, len(returns), 250))
    assert [returns.index.get_loc(d) for d in forecasts.refit_dates] == expected


def test_heavy_models_are_refitted_less_often(returns, features):
    """A network flagged ``heavy`` is retrained annually, not monthly."""
    calls: list[int] = []

    class Counting(volmodels.VolatilityModel):
        name = "counting"
        heavy = True

        def fit(self, returns, features, end):
            calls.append(end)

        def forecast(self, returns, features, start, stop):
            return np.full(stop - start, float(np.var(np.asarray(returns[:stop], dtype=float))))

    model = Counting()
    volmodels.walk_forward([model], returns, features, init_window=1_000, refit_every=21, nn_refit_every=250)
    assert len(calls) >= 2
    gaps = np.diff(calls)
    assert np.all(gaps >= 250)


def test_walk_forward_rejects_a_window_that_leaves_nothing(returns, features):
    zoo = [volmodels.EWMA(lam=0.94)]
    with pytest.raises(ValueError, match="leaves no evaluation sample"):
        volmodels.walk_forward(zoo, returns, features, init_window=len(returns))


def test_every_model_in_the_default_zoo_has_a_unique_name():
    zoo = volmodels.default_model_zoo(fast=True)
    names = [m.name for m in zoo]
    assert len(names) == len(set(names))
    # `fast` reduces the training budget; it must not remove a contestant.
    assert "gru" in names
    assert "monte_carlo" not in names  # that is a VaR method, not a vol model
    assert len(names) == 11


def test_the_zoo_matches_the_declared_roster():
    """The declared names and the constructed ones are compared, not assumed equal.

    ``config.MODEL_NAMES`` is what the documentation renderer checks its tables against;
    the zoo is what actually runs. If they diverge, the renderer either refuses to
    publish or - worse, before that check existed - publishes a report describing a
    study that was not the one performed.
    """
    assert tuple(m.name for m in volmodels.default_model_zoo()) == cfg.MODEL_NAMES
    assert tuple(m.name for m in volmodels.default_model_zoo(fast=True)) == cfg.MODEL_NAMES
