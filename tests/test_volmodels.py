"""Tests for the volatility-model family and the walk-forward engine.

Two classes of claim are checked. The first is that each model implements the
recursion it advertises - a rolling window that matches a naive loop, an EWMA that
matches its own definition, an EGARCH that stays positive by construction. The
second is that no model can see the future: fitting on data up to ``T`` and
forecasting ``T`` must produce the same number whether or not the series after
``T`` exists. That second claim is the one that matters, because breaking it makes
every downstream result better and no downstream test will complain.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from marketrisk import config as cfg
from marketrisk import kernels, volmodels


# ---------------------------------------------------------------------------
# Benchmarks
# ---------------------------------------------------------------------------
def test_rolling_variance_matches_a_naive_loop():
    rng = np.random.default_rng(21)
    r = rng.standard_normal(500) * 0.01
    features = pd.DataFrame(index=pd.RangeIndex(500))
    model = volmodels.RollingVariance(window=21)
    got = model.forecast(r, features, 100, 140)
    for offset, i in enumerate(range(100, 140)):
        window = r[:i][-21:] if i >= 21 else r[:i]
        assert got[offset] == pytest.approx(float(np.mean(window**2)), rel=1e-9)


def test_ewma_matches_its_own_recursion():
    """Replicate the kernel's seeding convention, including the first step.

    At ``t = 0`` there is no previous return, so the recursion contributes nothing
    and ``sigma2_0 = lam * backcast`` - the backcast is decayed once. A hand-written
    loop that starts from the undecayed backcast disagrees with the kernel at
    exactly one index and nowhere else, which is the kind of mismatch that looks
    like a tolerance problem and is not.
    """
    rng = np.random.default_rng(22)
    r = rng.standard_normal(300) * 0.01
    features = pd.DataFrame(index=pd.RangeIndex(300))
    model = volmodels.EWMA(lam=0.94)
    model.fit(r, features, 300)
    got = model.forecast(r, features, 0, 300)

    backcast = kernels.variance_backcast(r, cfg.GARCH_BACKCAST_WEIGHT)
    state = backcast
    for t in range(300):
        state = 0.94 * state + 0.06 * (r[t - 1] ** 2 if t > 0 else 0.0)
        assert got[t] == pytest.approx(state, rel=1e-9)


def test_fitted_ewma_chooses_from_the_grid(returns, features):
    model = volmodels.EWMA(fit_decay=True)
    model.reset()
    model.fit(returns.to_numpy(dtype=float), features, len(returns))
    assert model.chosen in cfg.EWMA_LAMBDA_GRID
    assert model.name == "ewma_fitted"


def test_reset_restores_the_published_decay():
    model = volmodels.EWMA(lam=0.94, fit_decay=True)
    model.chosen = 0.99
    model.reset()
    assert model.chosen == 0.94


