def test_har_design_matrix_is_well_conditioned(features):
    """``rv_slope`` must not be in the HAR design.

    It is defined as ``log_rv_w - log_rv_m``. With both components also present the
    design is exactly singular: the condition number reaches 1e16 and the
    least-squares solution is determined entirely by the ridge penalty, which is a
    number chosen for numerical safety rather than for any statistical reason.
    """
    model = volmodels.HAR(use_vix=True)
    x, _ = model._design(features, 1_500)
    x = x[np.isfinite(x).all(axis=1)]
    assert "rv_slope" not in model.columns
    assert np.linalg.cond(x) < 1e6
    assert float(np.linalg.svd(x, compute_uv=False)[-1]) > 0.0


def test_har_coefficients_have_the_expected_signs(returns, features):
    model = volmodels.HAR(use_vix=False)
    model.fit(returns.to_numpy(dtype=float), features, 1_500)
    assert model.coef is not None
    assert (model.coef[1:4] > 0).all()


def test_har_applies_the_lognormal_smearing_correction(returns, features):
    """``E[RV] = exp(mu + s^2/2)``; without the correction every forecast is low."""
    model = volmodels.HAR(use_vix=False)
    model.fit(returns.to_numpy(dtype=float), features, 1_500)
    assert model.residual_variance > 0.0

    out = model.forecast(returns.to_numpy(dtype=float), features, 1_500, 1_520)
    block = features.iloc[1_500:1_520]
    base = model.columns[1:]
    x = np.column_stack([np.ones(len(block)), block[base].to_numpy(dtype=float)])
    without = np.exp(x @ model.coef)
    ratio = out / without
    assert np.allclose(ratio, np.exp(0.5 * model.residual_variance), rtol=1e-9)


def test_harx_uses_the_extra_regressors():
    plain = volmodels.HAR(use_vix=False)
    extended = volmodels.HAR(use_vix=True)
    assert plain.name == "har"
    assert extended.name == "harx"


def test_har_reads_the_feature_frame_not_the_return_series(returns, features):
    """A legality property with a structural cause, worth stating explicitly.

    HAR consumes the *lagged feature matrix*, not the raw return array. Poisoning
    the return series therefore cannot move a HAR forecast even if the poison were
    placed in the past - the model never reads that array. The guarantee that the
    features themselves are lagged correctly lives in ``test_features.py``; this
    test pins down that HAR is downstream of that guarantee rather than
    re-deriving it from returns.
    """
    model = volmodels.HAR(use_vix=True)
    r = returns.to_numpy(dtype=float)
    model.fit(r, features, 1_500)
    baseline = model.forecast(r, features, 1_500, 1_560)
    poisoned = r.copy()
    poisoned[:] *= 9.0
    assert np.allclose(baseline, model.forecast(poisoned, features, 1_500, 1_560), rtol=1e-12)


